output_filepath = Path("dataset.json.gz")
progress_filepath = Path("dataset.progress.json")


def save_checkpoint(dataset: list, next_index: int) -> None:
    """Persist the dataset and next manifest index so interrupted runs resume safely."""
    dataset_tmp = output_filepath.with_suffix(".json.gz.tmp")
    progress_tmp = progress_filepath.with_suffix(".json.tmp")

    with gzip.open(dataset_tmp, "wt", encoding="utf-8") as f:
        json.dump(dataset, f, ensure_ascii=False)
    with progress_tmp.open("w", encoding="utf-8") as f:
        json.dump({"next_index": next_index}, f)

    os.replace(dataset_tmp, output_filepath)
    os.replace(progress_tmp, progress_filepath)


def make_dataset_item(manifest_item: dict) -> dict:
    """Keep source fields explicit so Goodreads and Gutenberg data cannot be confused."""
    item = {}
    source_field_names = {
        "title": "goodreads_title",
        "isbn": "goodreads_isbn",
        "first_published": "goodreads_first_published",
        "num_reviews": "goodreads_num_reviews",
    }

    for key, value in manifest_item.items():
        if key in source_field_names:
            item[source_field_names[key]] = value
        elif key.startswith("goodreads_") or key.startswith("gutenberg_"):
            item[key] = value
        else:
            item[f"gutenberg_{key}"] = value

    return item


