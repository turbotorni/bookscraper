def fetch_book_content(book_id: int, max_sentences: int = 1000):
    """Downloads plain text, strips front-matter, and returns tokenized sentences

    or full text depending on max_sentences (None for full text).
    """
    urls = [
        f"https://www.gutenberg.org/files/{book_id}/{book_id}-0.txt",
        f"https://www.gutenberg.org/cache/epub/{book_id}/pg{book_id}.txt",
    ]

    raw_text = ""
    for url in urls:
        try:
            resp = requests.get(url, headers=HEADERS, timeout=15)
            if resp.status_code == 200:
                raw_text = resp.text
                break
        except Exception:
            continue

    if not raw_text:
        return None, 0

    # Clean front-matter and TOC
    cleaned_body = strip_preamble_and_toc(raw_text)

    # Return full text mode if max_sentences is set to None
    if max_sentences is None:
        return cleaned_body, len(nltk.sent_tokenize(cleaned_body))

    # Tokenize into clean sentences
    raw_sentences = nltk.sent_tokenize(cleaned_body)
    clean_sentences = [
        re.sub(r"\s+", " ", s).strip() for s in raw_sentences if s.strip()
    ]

    selected_sentences = clean_sentences[:max_sentences]
    return selected_sentences, len(selected_sentences)

