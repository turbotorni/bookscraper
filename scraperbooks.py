def get_genres_for_book(book_id: int) -> list:
    """Visits the main page for a recommended book to extract its genres/subjects/bookshelves."""
    url = f"https://www.gutenberg.org/ebooks/{book_id}"
    genres = []

    try:
        response = requests.get(url, headers=HEADERS, timeout=10)
        if response.status_code != 200:
            return genres

        soup = BeautifulSoup(response.text, "html.parser")

        # 1. Look for Bookshelves/Categories and Subjects in the metadata table
        bibrec = soup.find("table", class_="bibrec")
        if bibrec:
            for row in bibrec.find_all("tr"):
                th = row.find("th")
                if th and ("Subject" in th.text or "Category" in th.text):
                    td = row.find("td")
                    if td:
                        for a in td.find_all("a"):
                            genre_text = a.text.strip()
                            if genre_text and genre_text not in genres:
                                genres.append(genre_text)

    except Exception as e:
        print(f"Error fetching genres for book {book_id}: {e}")

    return genres


def scrape_related_books_and_genres(book_id: int, max_related: int = 5):
    """Scrape related Gutenberg book IDs and titles from the /also/ page."""
    also_url = f"https://www.gutenberg.org/ebooks/{book_id}/also/"
    print(f"Fetching related books from: {also_url}")

    response = requests.get(also_url, headers=HEADERS, timeout=12)
    if response.status_code != 200:
        print(f"Failed to load /also/ page. Status code: {response.status_code}")
        return []

    soup = BeautifulSoup(response.text, "html.parser")
    related_books = []

    # Book links on Gutenberg's /also/ page appear inside list items or table entries matching /ebooks/\d+
    # Matches <a href="/ebooks/1234">Title</a>
    book_links = soup.find_all("a", href=re.compile(r"^/ebooks/(\d+)$"))

    seen_ids = set()

    for link in book_links:
        href = link.get("href")
        match = re.search(r"^/ebooks/(\d+)$", href)
        if not match:
            continue

        rel_id = int(match.group(1))

        # Skip duplicates or the original book itself
        if rel_id in seen_ids or rel_id == book_id:
            continue

        seen_ids.add(rel_id)

        title = link.text.strip()
        downloads = None
        downloads_tag = link.find("span", class_="extra")
        if downloads_tag:
            downloads_match = re.search(r"([\d,]+)\s+downloads?", downloads_tag.get_text(" ", strip=True))
            if downloads_match:
                downloads = int(downloads_match.group(1).replace(",", ""))

        print(
            f"Found Related Book ID: {rel_id} | "
            f"Title: {title} | Downloads: {downloads}"
        )

        related_books.append({
            "book_id": rel_id,
            "title": title,
            "downloads": downloads,
        })

        if len(related_books) >= max_related:
            break

    return related_books

def scrape_gutenberg_metadata(book_id: int, max_related: int = 10) -> dict:
    """Takes an HTML snapshot of the Gutenberg book page to extract metadata,

    download counts, author, title, summary, AND proposed/related books.
    """
    url = f"https://www.gutenberg.org/ebooks/{book_id}"

    # metadata_result = {
    #     "metadata_table": {},
    #     "related_books": [],
    #     "summary": None,
    # }

    metadata_result = {}

    try:
        response = requests.get(url, headers=HEADERS, timeout=12)
        if response.status_code != 200:
            print(f"[METADATA FAILED] ID {book_id} HTTP {response.status_code}")

        soup = bs4.BeautifulSoup(response.text, "html.parser")



        # 5. Extract Full Bibliographic Metadata Table
        bibrec_table = soup.find("table", class_="bibrec")
        if bibrec_table:
            for row in bibrec_table.find_all("tr"):
                th = row.find("th")
                td = row.find("td")
                if th and td:
                    key = th.text.strip().replace(":", "")
                    val = " ".join(td.text.split())
                    metadata_result[key] = val

        # 3. Extract Summary
        summary_tag = soup.find("div", class_="bibrec_summary")
        if summary_tag:
            metadata_result["summary"] = summary_tag.text.strip()

        # 6. Extract Related/Proposed Books from /also/ Page
        if max_related > 0:
            metadata_result["related_books"] = scrape_related_books_and_genres(book_id=book_id, max_related=max_related)

    except Exception as e:
        print(f"Error scraping metadata snapshot for ID {book_id}: {e}")

    return metadata_result

def strip_preamble_and_toc(text: str) -> str:
    """Strips standard Gutenberg headers, footers, and skips front-matter (TOC,

    prefaces, title blocks) to start at actual story narrative.
    """
    # 1. Strip standard Gutenberg license headers
    start_match = re.search(
        r"\*\*\*\s*START OF TH(IS|E) PROJECT GUTENBERG EBOOK.*?\*\*\*",
        text,
        re.IGNORECASE,
    )
    if start_match:
        text = text[start_match.end() :]

    # 2. Strip Gutenberg license footers
    end_match = re.search(
        r"\*\*\*\s*END OF TH(IS|E) PROJECT GUTENBERG EBOOK",
        text,
        re.IGNORECASE,
    )
    if end_match:
        text = text[: end_match.start()]

    # 3. Skip front-matter / Table of Contents / Preface
    paragraphs = text.split("\n\n")
    start_paragraph_idx = 0

    for idx, p in enumerate(paragraphs):
        p_clean = p.strip()

        # Look for chapter markers or substantial narrative paragraphs (> 150 chars with sentence punctuation)
        if (
            re.match(r"^(CHAPTER|BOOK|PART|ACT|SECTION)\s+[IVXLCDM\d]+", p_clean, re.IGNORECASE)
            or (len(p_clean) > 150 and re.search(r"[\.\!\?]", p_clean))
        ):
            # Skip if paragraph is just TOC dot-lines (e.g., "Chapter 1 .......... 15")
            if "..." not in p_clean and ". . ." not in p_clean:
                start_paragraph_idx = idx
                break

    return "\n\n".join(paragraphs[start_paragraph_idx:]).strip()


